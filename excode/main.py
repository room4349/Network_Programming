first = int(input("첫 번째 정수를 입력하세요: "))
second = int(input("두 번째 정수를 입력하세요: "))

print("{} + {} = {}".format(first, second, first + second))
print("{} - {} = {}".format(first, second, first - second))
print("{} x {} = {}".format(first, second, first * second))
print("{} / {} = {}".format(first, second, first / second))
